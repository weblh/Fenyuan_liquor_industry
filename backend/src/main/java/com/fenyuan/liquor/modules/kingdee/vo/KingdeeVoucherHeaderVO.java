package com.fenyuan.liquor.modules.kingdee.vo;

public class KingdeeVoucherHeaderVO {

    private String voucherId;
    private String voucherNumber;
    private String voucherGroupNumber;
    private String voucherGroupName;

    public String getVoucherId() {
        return voucherId;
    }

    public void setVoucherId(String voucherId) {
        this.voucherId = voucherId;
    }

    public String getVoucherNumber() {
        return voucherNumber;
    }

    public void setVoucherNumber(String voucherNumber) {
        this.voucherNumber = voucherNumber;
    }

    public String getVoucherGroupNumber() {
        return voucherGroupNumber;
    }

    public void setVoucherGroupNumber(String voucherGroupNumber) {
        this.voucherGroupNumber = voucherGroupNumber;
    }

    public String getVoucherGroupName() {
        return voucherGroupName;
    }

    public void setVoucherGroupName(String voucherGroupName) {
        this.voucherGroupName = voucherGroupName;
    }
}